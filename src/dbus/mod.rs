use std::collections::HashMap;

use zbus::OwnedVariant;

/// The D-Bus operations the host performs, as an interface.  `Connection`
/// implements this by issuing real calls; tests mock it with
/// `MockDbus` (generated by `mockall` in test builds).
///
/// Async traits are not object-safe, so the operations are consumed through
/// generics (`D: Dbus + ?Sized`) rather than `dyn Dbus`.
#[cfg_attr(test, mockall::automock)]
#[cfg_attr(
    test,
    allow(
        clippy::unused_async_trait_impl,
        reason = "mock methods dispatch through expectations, they do not .await"
    )
)]
pub(crate) trait Dbus: Send + Sync {
    /// Fetch every property of the object at `path` (`Properties.GetAll`).
    async fn fetch_all_props(&self, path: &str) -> Result<HashMap<String, OwnedVariant>>;

    /// Enumerate the visible device ids via the daemon's `devices` call.
    async fn list_device_ids(&self) -> Result<Vec<String>>;

    /// Send a URL to a device via the `kdeconnect_share` plugin.
    async fn share_url(&self, device_id: &str, url: &str) -> Result<()>;

    /// Register one D-Bus `AddMatch` rule.
    async fn add_match(&self, rule: &str) -> Result<()>;
}

impl Dbus for Connection {
    async fn fetch_all_props(&self, path: &str) -> Result<HashMap<String, OwnedVariant>> {
        props::fetch_all_props(self, path).await
    }

    async fn list_device_ids(&self) -> Result<Vec<String>> {
        devices::list_device_ids(self).await
    }

    async fn share_url(&self, device_id: &str, url: &str) -> Result<()> {
        share_url(self, device_id, url).await
    }

    async fn add_match(&self, rule: &str) -> Result<()> {
        matchers::add_match_rule(self, rule).await
    }
}

/// Thread-safe handle to a device's mutable state.
pub(crate) type SharedDevice = Arc<Mutex<DeviceState>>;

/// Mutable device state kept in sync with D-Bus properties.
pub(crate) struct DeviceState {
    /// The device's cached state.
    pub device: Device,
    /// D-Bus object path of the device.
    pub object_path: String,
}

/// Open a session-bus connection.
pub(crate) async fn open_connection() -> Result<Connection> {
    Connection::session().await.context("open session bus")
}
